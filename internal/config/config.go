package config

import (
	"fmt"
	"os"
	"time"

	"gopkg.in/yaml.v3"
)

// Config is the root configuration loaded from config.yaml.
// All values are set by the setup wizard — there are no hardcoded defaults.
type Config struct {
	Server   ServerConfig   `yaml:"server"`
	Database DatabaseConfig `yaml:"database"`
	Cache    CacheConfig    `yaml:"cache"`
	Chat     ChatConfig     `yaml:"chat"`
	Admin    AdminConfig    `yaml:"admin"`
}

type ServerConfig struct {
	Host           string   `yaml:"host"`
	Port           int      `yaml:"port"`
	Debug          bool     `yaml:"debug"`
	SecretKey      string   `yaml:"secret_key"`
	AllowedOrigins []string `yaml:"allowed_origins"`
	CountryHeaders []string `yaml:"country_headers"`
}

type DatabaseConfig struct {
	Host            string `yaml:"host"`
	Port            int    `yaml:"port"`
	Name            string `yaml:"name"`
	User            string `yaml:"user"`
	Password        string `yaml:"password"`
	TLS             bool   `yaml:"tls"`
	MaxOpenConns    int    `yaml:"max_open_conns"`
	MaxIdleConns    int    `yaml:"max_idle_conns"`
	ConnMaxLifetime int    `yaml:"conn_max_lifetime"`
}

type CacheConfig struct {
	Host     string `yaml:"host"`
	Port     int    `yaml:"port"`
	Password string `yaml:"password"`
	DB       int    `yaml:"db"`
	TLS      bool   `yaml:"tls"`
}

type ChatConfig struct {
	MaxMessageLength int    `yaml:"max_message_length"`
	MaxHistory       int    `yaml:"max_history"`
	RateLimit        int    `yaml:"rate_limit_seconds"`
	AllowAnonymous   bool   `yaml:"allow_anonymous"`
	SiteName         string `yaml:"site_name"`
	Notice           string `yaml:"notice"`
}

type AdminConfig struct {
	Path string `yaml:"path"`
}

// IsInstalled returns true when config.yaml already exists.
func IsInstalled(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// Load reads and unmarshals the YAML configuration file.
func Load(path string) (*Config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read config: %w", err)
	}
	var cfg Config
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}
	return &cfg, nil
}

// Save writes cfg to path as a commented YAML file.
func Save(path string, cfg *Config) error {
	content := renderYAML(cfg)
	return os.WriteFile(path, []byte(content), 0600)
}

func renderYAML(cfg *Config) string {
	origins := ""
	for _, o := range cfg.Server.AllowedOrigins {
		origins += fmt.Sprintf("    - %q\n", o)
	}
	if origins == "" {
		origins = "    - \"*\"\n"
	}
	countryHdrs := ""
	for _, h := range cfg.Server.CountryHeaders {
		countryHdrs += fmt.Sprintf("    - %q\n", h)
	}
	if countryHdrs == "" {
		countryHdrs = "    - \"CF-IPCountry\"\n    - \"X-Country\"\n"
	}

	return fmt.Sprintf(`# ============================================================
# ChatSphere — Configuration File
# Generated by the setup wizard on %s
#
# This file is chmod 600. Do NOT commit it to version control.
# To re-run the setup wizard, delete this file and restart.
# ============================================================

# ────────────────────────────────────────────────────────────
# HTTP Server
# ────────────────────────────────────────────────────────────
server:
  # Bind address. Use 0.0.0.0 to listen on all interfaces.
  host: %q

  # HTTP port exposed to the internet (or reverse proxy).
  port: %d

  # Debug mode — verbose request logging and panic recovery traces.
  # Set to false in production.
  debug: %v

  # JWT signing secret. Auto-generated during setup.
  # Changing this invalidates all active user sessions.
  secret_key: %q

  # CORS — a list of origins permitted to embed the widget or call the API.
  # Use ["*"] to allow any origin (fine for public chat; tighter for private).
  allowed_origins:
%s
  # Headers checked (in order) for the visitor's ISO-3166-1 alpha-2 country code.
  # First non-empty 2-letter value wins. Add or reorder for your CDN:
  #   Cloudflare:     CF-IPCountry
  #   Tencent EdgeOne: EO-Client-Country-Region
  #   Custom header:  <your header name>
  country_headers:
%s
# ────────────────────────────────────────────────────────────
# Database (MySQL 8.0+ / TiDB)
# ────────────────────────────────────────────────────────────
database:
  # MySQL host (IP or hostname)
  host: %q

  # MySQL port (default: 3306)
  port: %d

  # Database / schema name
  name: %q

  # Database user
  user: %q

  # Database password — stored with mode 0600, never logged
  password: %q

  # Enable TLS/SSL — set true for TiDB Cloud and other managed databases
  tls: %v

  # Maximum number of open connections to the database
  max_open_conns: %d

  # Maximum number of idle connections kept in the pool
  max_idle_conns: %d

  # Maximum time (seconds) a connection may be reused; 0 = unlimited
  conn_max_lifetime: %d

# ────────────────────────────────────────────────────────────
# Cache (Redis / Upstash)
# ────────────────────────────────────────────────────────────
cache:
  # Redis host
  host: %q

  # Redis port (default: 6379)
  port: %d

  # Redis AUTH password — leave empty if authentication is disabled
  password: %q

  # Redis logical database index (0–15)
  db: %d

  # Enable TLS/SSL — set true for Upstash Redis and other managed Redis services
  tls: %v

# ────────────────────────────────────────────────────────────
# Chat Behaviour
# ────────────────────────────────────────────────────────────
chat:
  # Site / product name shown in the widget header
  site_name: %q

  # Notice text shown in the collapsible banner inside the widget
  notice: %q

  # Maximum characters allowed per message
  max_message_length: %d

  # Number of messages kept per channel (oldest evicted when exceeded)
  max_history: %d

  # Minimum seconds a user must wait between messages (per connection)
  rate_limit_seconds: %d

  # Allow visitors to send messages without registering an account
  allow_anonymous: %v

# ────────────────────────────────────────────────────────────
# Admin Panel
# ────────────────────────────────────────────────────────────
admin:
  # URL path prefix for the admin panel
  path: %q
`,
		time.Now().Format("2006-01-02 15:04:05"),
		cfg.Server.Host,
		cfg.Server.Port,
		cfg.Server.Debug,
		cfg.Server.SecretKey,
		origins,
		countryHdrs,
		cfg.Database.Host,
		cfg.Database.Port,
		cfg.Database.Name,
		cfg.Database.User,
		cfg.Database.Password,
		cfg.Database.TLS,
		cfg.Database.MaxOpenConns,
		cfg.Database.MaxIdleConns,
		cfg.Database.ConnMaxLifetime,
		cfg.Cache.Host,
		cfg.Cache.Port,
		cfg.Cache.Password,
		cfg.Cache.DB,
		cfg.Cache.TLS,
		cfg.Chat.SiteName,
		cfg.Chat.Notice,
		cfg.Chat.MaxMessageLength,
		cfg.Chat.MaxHistory,
		cfg.Chat.RateLimit,
		cfg.Chat.AllowAnonymous,
		cfg.Admin.Path,
	)
}
